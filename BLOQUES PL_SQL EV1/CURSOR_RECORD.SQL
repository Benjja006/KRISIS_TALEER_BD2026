/*COMO ADMINISTRADOR DE KRISIS QUIERO CONSULTAR EL TOP FAN DE UN ARTISTA EN UN PAÍS ESPECÍFICO PARA OTORGARLE ACCESO ANTICIPADO
  *KRISIS DEBE PERMITIR CONSULTAR EL USUARIO CON MÁS SEGUNDOS REPRODUCIDOS DE UN ARTISTA Y PAÍS MEDIANTE UN CURSOR CON PARÁMETROS Y ALMACENARLO EN UN RECORD, SI NO EXISTEN REPRODUCCIONES DEBE INFORMAR QUE NO HAY REGISTROS*/

SET SERVEROUTPUT ON;

DECLARE 
    TYPE R_TOP_FAN IS RECORD( 
        USERNAME USUARIO.NOMBRE_USUARIO%TYPE, 
        CORREO USUARIO.EMAIL%TYPE, 
        NOMBRE_PAIS PAIS.NOMBRE%TYPE, 
        TOTAL_SEGUNDOS NUMBER 
    );
    V_FAN R_TOP_FAN;

    CURSOR C_TOP_FAN(P_ID_ARTISTA NUMBER, P_ID_PAIS NUMBER) IS 
        SELECT 
            U.NOMBRE_USUARIO,
            U.EMAIL,
            P.NOMBRE AS PAIS,
            SUM(S.SEGUNDOS_REPRODUCIDOS) AS TOTAL_SEGUNDOS
        FROM STREAM_LOG S
        INNER JOIN USUARIO U ON U.ID_USUARIO = S.ID_USUARIO
        INNER JOIN PAIS P ON P.ID_PAIS = S.ID_PAIS
        INNER JOIN CANCION C ON C.ID_CANCION = S.ID_CANCION
        INNER JOIN ALBUM AL ON AL.ID_ALBUM = C.ID_ALBUM
        INNER JOIN ALBUM_ARTISTA AA ON AA.ALBUM_ID_ALBUM = AL.ID_ALBUM
        WHERE AA.ARTISTA_ID_ARTISTA = P_ID_ARTISTA AND S.ID_PAIS = P_ID_PAIS
        GROUP BY U.NOMBRE_USUARIO, U.EMAIL, P.NOMBRE
        ORDER BY TOTAL_SEGUNDOS DESC;

    V_ENCONTRADO NUMBER := 0;
    E_SIN_REPRODUCCIONES EXCEPTION;

BEGIN 
    FOR REGISTRO IN C_TOP_FAN(1, 1) LOOP
        V_FAN.USERNAME := REGISTRO.NOMBRE_USUARIO;
        V_FAN.CORREO := REGISTRO.EMAIL;
        V_FAN.NOMBRE_PAIS := REGISTRO.PAIS;
        V_FAN.TOTAL_SEGUNDOS := REGISTRO.TOTAL_SEGUNDOS;

        DBMS_OUTPUT.PUT_LINE('---TOP FAN EN '|| V_FAN.NOMBRE_PAIS ||'---');
        DBMS_OUTPUT.PUT_LINE('NOMBRE USUARIO: ' || V_FAN.USERNAME);
        DBMS_OUTPUT.PUT_LINE('EMAIL: ' || V_FAN.CORREO);
        DBMS_OUTPUT.PUT_LINE('SEGUNDOS REPRODUCIDOS: ' || V_FAN.TOTAL_SEGUNDOS);
        DBMS_OUTPUT.PUT_LINE('BENEFICIO: ACCESO ANTICIPADO HABILITADO');
        DBMS_OUTPUT.PUT_LINE('--------------------------------------------------------');
    
        V_ENCONTRADO := 1;
        EXIT;
    END LOOP;

    IF V_ENCONTRADO = 0 THEN
        RAISE E_SIN_REPRODUCCIONES;
    END IF;

EXCEPTION 
    WHEN E_SIN_REPRODUCCIONES THEN
        DBMS_OUTPUT.PUT_LINE('NO SE ENCONTRARON REPRODUCCIONES PARA EL ARTISTA Y PAIS CONSULTADO.');

    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERROR INESPERADO');
END;
