/*COMO USUARIO DE KRISIS QUIERO CONSULTAR INFORMACIÓN DE MI PERFIL PARA CONOCER MIS DATOS REGISTRADOS, MI PAÍS Y SI POSEO BENEFICIOS PREMIUM
    PERMITIR CONSULTAR EL PERFIL DEL USUARIO MEDIANTE SU ID, MOSTRANDO SU NOMBRE, CORREO,
    PAÍS Y ESTADO PREMIUM, SI EL USUARIO NO EXISTE, EL SISTEMA DEBE INFORMAR QUE NO SE ENCONTRÓ*/

DECLARE 

    TYPE R_DATOS_USUARIO IS RECORD(
        NOMBRE_USUARIO USUARIO.NOMBRE_USUARIO%TYPE,
        EMAIL USUARIO.EMAIL%TYPE,
        NOMBRE_PAIS PAIS.NOMBRE%TYPE,
        ES_PREMIUM USUARIO.ES_PREMIUM%TYPE 
    );

    V_USUARIO R_DATOS_USUARIO;
    E_USUARIO_NO_PREMIUM EXCEPTION;
BEGIN 

    SELECT 
        U.NOMBRE_USUARIO,
        U.EMAIL,
        P.NOMBRE,
        U.ES_PREMIUM
    INTO V_USUARIO
    FROM USUARIO U
    INNER JOIN PAIS P ON P.ID_PAIS = U.PAIS_ID_PAIS
    WHERE U.ID_USUARIO = 3;

        DBMS_OUTPUT.PUT_LINE('---INFO USUARIO '|| V_USUARIO.NOMBRE_USUARIO||'---');
        DBMS_OUTPUT.PUT_LINE('NOMBRE USUARIO: ' || V_USUARIO.NOMBRE_USUARIO);
        DBMS_OUTPUT.PUT_LINE('EMAIL: '|| V_USUARIO.EMAIL);
        DBMS_OUTPUT.PUT_LINE('PAIS: ' || V_USUARIO.NOMBRE_PAIS);

        IF V_USUARIO.ES_PREMIUM = 1 then
        DBMS_OUTPUT.PUT_LINE('USUARIO PREMIUM ');

        ELSE 
            RAISE E_USUARIO_NO_PREMIUM;
        END IF;
    EXCEPTION 
    
        WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('El usuario es inextistente.');
    
        WHEN TOO_MANY_ROWS THEN
        DBMS_OUTPUT.PUT_LINE('ERROR: SE ENCONTRÓ MAS DE UN USUARIO.');

        WHEN E_USUARIO_NO_PREMIUM THEN
        DBMS_OUTPUT.PUT_LINE('USUARIO NO PREMIUM');
    
        WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERROR INTESPERADO');
END;
/











